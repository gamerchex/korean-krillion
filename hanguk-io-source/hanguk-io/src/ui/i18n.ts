const TABLES: Record<UiLang, Record<StringKey, string>> = { en, ko };

export function t(lang: UiLang, key: StringKey, vars?: Record<string, string | number>): string {
  let s = TABLES[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function fmtPct(p: number): string {
  const pct = p * 100;
  if (pct >= 10) return `${Math.round(pct)}%`;
  if (pct >= 1) return `${pct.toFixed(1)}%`;
  if (pct >= 0.1) return `${pct.toFixed(2)}%`;
  return '<0.1%';
}

/** An estimated share in words: "about 8%" / "fewer than 0.1%" (약 8% / 0.1% 미만). */
export function fmtShare(p: number, lang: UiLang): string {
  if (p * 100 < 0.1) return lang === 'ko' ? '0.1% 미만' : 'fewer than 0.1%';
  return lang === 'ko' ? `약 ${fmtPct(p)}` : `about ${fmtPct(p)}`;
}

export function fmtDuration(ms: number): string {
  const s = Math.max(0, Math.floor(ms / 1000));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = s % 60;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')}`;
}

export function fmtDate(dateKey: string, lang: UiLang): string {
  const [y, m, d] = dateKey.split('-').map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d));
  const wd = dt.getUTCDay();
  if (lang === 'ko') return `${y}년 ${m}월 ${d}일 (${'일월화수목금토'[wd]})`;
  const mon = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'][m - 1];
  return `${['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'][wd]} ${d} ${mon} ${y}`;
}

export function fmtMeters(m: number): string {
  return `${Math.round(m).toLocaleString('en-US')} m`;
}

